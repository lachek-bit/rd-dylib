#import <Foundation/Foundation.h>

NSString *RDIndexHTML(void);

NSString *RDIndexHTML(void) {
    return
    @"<!doctype html>\n"
    @"<html lang='zh'><head><meta charset='utf-8'>\n"
    @"<meta name='viewport' content='width=device-width,initial-scale=1'>\n"
    @"<title>RemoteDebug</title><style>\n"
    @"*{box-sizing:border-box}\n"
    @"html,body{margin:0;height:100%;background:#0e1116;color:#c9d1d9;font:13px/1.55 ui-monospace,SFMono-Regular,Menlo,Consolas,monospace}\n"
    @"body{display:flex;flex-direction:column;height:100vh;overflow:hidden}\n"
    @"header{padding:8px 12px;background:#161b22;border-bottom:1px solid #21262d;display:flex;gap:10px;align-items:center;flex-wrap:wrap;font-size:12px;flex:none}\n"
    @"header b{color:#e6edf3;font-size:13px}\n"
    @".dot{width:8px;height:8px;border-radius:50%;background:#f85149;box-shadow:0 0 6px #f85149}\n"
    @".dot.on{background:#3fb950;box-shadow:0 0 6px #3fb950}\n"
    @"#info{color:#8b949e}\n"
    @"#log{flex:1;overflow:auto;padding:6px 12px;white-space:pre-wrap;word-break:break-all}\n"
    @".ln{display:flex;gap:8px;padding:1px 0;border-bottom:1px solid #12171e}\n"
    @".t{color:#484f58;flex:none;user-select:none}\n"
    @".s{flex:1;min-width:0}\n"
    @".err .s{color:#ff7b72}\n"
    @".in .s{color:#79c0ff}\n"
    @"#tools{display:none;padding:8px 12px;background:#0b0f14;border-bottom:1px solid #21262d;max-height:36vh;overflow:auto;flex-wrap:wrap;gap:6px;align-items:flex-start}\n"
    @"#tools.show{display:flex}\n"
    @"#tools .gtitle{width:100%;color:#6e7681;font-size:11px;margin:4px 0 0;letter-spacing:.06em}\n"
    @".tool{background:#1c2128;border:1px solid #30363d;color:#adbac7;padding:5px 10px;border-radius:5px;cursor:pointer;font:12px ui-monospace,Menlo,monospace}\n"
    @".tool:hover{background:#2d333b;border-color:#539bf5;color:#e6edf3}\n"
    @".tool:active{transform:translateY(1px)}\n"
    @"footer{background:#161b22;border-top:1px solid #21262d;padding:8px 12px;display:flex;gap:8px;align-items:center;flex:none}\n"
    @"input{flex:1;min-width:0;background:#0d1117;border:1px solid #30363d;color:#c9d1d9;padding:8px 10px;border-radius:6px;font:inherit;outline:none}\n"
    @"input:focus{border-color:#388bfd;box-shadow:0 0 0 2px #388bfd33}\n"
    @"button{background:#21262d;border:1px solid #30363d;color:#c9d1d9;padding:7px 12px;border-radius:6px;cursor:pointer;font:inherit;white-space:nowrap}\n"
    @"button:hover{background:#30363d;border-color:#8b949e}\n"
    @"button:active{transform:translateY(1px)}\n"
    @"</style></head><body>\n"
    @"<header>\n"
    @"  <span class='dot' id='dot'></span>\n"
    @"  <b id='title'>RemoteDebug</b>\n"
    @"  <span id='info'>connecting...</span>\n"
    @"  <span style='margin-left:auto'></span>\n"
    @"  <button id='bshot'>截图</button>\n"
    @"  <button id='bui'>UI 树</button>\n"
    @"  <button id='bvc'>VC 栈</button>\n"
    @"  <button id='bcls'>类搜索</button>\n"
    @"  <button id='bhooks'>Hooks</button>\n"
    @"  <button id='btools'>工具</button>\n"
    @"  <button id='bcls2'>日志开关</button>\n"
    @"  <button id='bclear'>清屏</button>\n"
    @"</header>\n"
    @"<div id='tools'></div>\n"
    @"<div id='log'></div>\n"
    @"<footer>\n"
    @"  <input id='cmd' autocomplete='off' spellcheck='false' placeholder='ObjC 表达式，例：UIApplication.sharedApplication.keyWindow.frame  或  _rd.uiDump()'>\n"
    @"  <button id='brun'>执行</button>\n"
    @"</footer>\n"
    @"<script>\n"
    @"var logEl=document.getElementById('log');\n"
    @"var since=0, paused=false;\n"
    @"var M={'<':'&lt;','>':'&gt;','&':'&amp;'};\n"
    @"function esc(s){return String(s).replace(/[<>&]/g,function(c){return M[c];});}\n"
    @"function p2(n){return n<10?('0'+n):(''+n);}\n"
    @"function fmt(t){var d=new Date(t*1000);return p2(d.getHours())+':'+p2(d.getMinutes())+':'+p2(d.getSeconds());}\n"
    @"function append(lines){\n"
    @"  var stick=logEl.scrollTop+logEl.clientHeight>=logEl.scrollHeight-60;\n"
    @"  var frag=document.createDocumentFragment();\n"
    @"  for(var i=0;i<lines.length;i++){\n"
    @"    var l=lines[i];\n"
    @"    var row=document.createElement('div');\n"
    @"    row.className='ln'+(l.c?(' '+l.c):'');\n"
    @"    row.innerHTML='<span class=t>'+fmt(l.t)+'</span><span class=s>'+esc(l.s)+'</span>';\n"
    @"    frag.appendChild(row);\n"
    @"  }\n"
    @"  logEl.appendChild(frag);\n"
    @"  while(logEl.childElementCount>3000){logEl.removeChild(logEl.firstChild);}\n"
    @"  if(stick){logEl.scrollTop=logEl.scrollHeight;}\n"
    @"}\n"
    @"function say(s,c){append([{t:Date.now()/1000,s:s,c:c}]);logEl.scrollTop=logEl.scrollHeight;}\n"
    @"function setStatus(on,txt){\n"
    @"  document.getElementById('dot').className='dot'+(on?' on':'');\n"
    @"  if(txt){document.getElementById('info').textContent=txt;}\n"
    @"}\n"
    @"function loadInfo(){\n"
    @"  fetch('/api/info').then(function(r){return r.json();}).then(function(j){\n"
    @"    document.getElementById('title').textContent=j.app_name;\n"
    @"    document.title=j.app_name+' · RemoteDebug';\n"
    @"    setStatus(true,j.bundle_id+' '+j.version+' ('+j.build+') · '+j.device+' · iOS '+j.ios+' · pid '+j.pid+' · :'+j.port);\n"
    @"    say('connected  '+j.executable+'  '+j.bundle_path);\n"
    @"  }).catch(function(){setStatus(false);});\n"
    @"}\n"
    @"function poll(){\n"
    @"  if(paused){return;}\n"
    @"  fetch('/api/logs?since='+since,{cache:'no-store'}).then(function(r){return r.json();}).then(function(j){\n"
    @"    since=j.next||since;\n"
    @"    if(j.lines&&j.lines.length){append(j.lines);}\n"
    @"    setStatus(true);\n"
    @"  }).catch(function(){setStatus(false,'disconnected');});\n"
    @"}\n"
    @"function run(){\n"
    @"  var el=document.getElementById('cmd');\n"
    @"  var code=el.value.trim();\n"
    @"  if(!code){return;}\n"
    @"  say('>>> '+code,'in');\n"
    @"  el.value='';\n"
    @"  fetch('/api/eval',{method:'POST',body:code}).then(function(r){return r.json();}).then(function(j){\n"
    @"    if(j.ok){say(j.result);}else{say('ERROR: '+j.error,'err');}\n"
    @"  }).catch(function(e){say('fetch failed: '+e,'err');});\n"
    @"}\n"
    @"function textApi(url){\n"
    @"  fetch(url).then(function(r){return r.text();}).then(function(t){\n"
    @"    var lines=t.split('\\n');\n"
    @"    var arr=[];\n"
    @"    for(var i=0;i<lines.length;i++){if(lines[i].length){arr.push({t:Date.now()/1000,s:lines[i]});}}\n"
    @"    append(arr);\n"
    @"    logEl.scrollTop=logEl.scrollHeight;\n"
    @"  }).catch(function(e){say('fail: '+e,'err');});\n"
    @"}\n"
    @"var toolCache=[];\n"
    @"function loadTools(){\n"
    @"  fetch('/api/tools').then(function(r){return r.json();}).then(function(j){\n"
    @"    toolCache=j.tools||[];renderTools();\n"
    @"    document.getElementById('btools').textContent='工具('+toolCache.length+')';\n"
    @"  }).catch(function(){});\n"
    @"}\n"
    @"function renderTools(){\n"
    @"  var box=document.getElementById('tools');box.innerHTML='';\n"
    @"  var groups={},order=[];\n"
    @"  for(var i=0;i<toolCache.length;i++){\n"
    @"    var t=toolCache[i],g=t.group||'其他';\n"
    @"    if(!groups[g]){groups[g]=[];order.push(g);}\n"
    @"    groups[g].push(t);\n"
    @"  }\n"
    @"  for(var gi=0;gi<order.length;gi++){\n"
    @"    var g=order[gi];\n"
    @"    var h=document.createElement('div');h.className='gtitle';h.textContent=g;box.appendChild(h);\n"
    @"    for(var k=0;k<groups[g].length;k++){\n"
    @"      var tk=groups[g][k];\n"
    @"      var b=document.createElement('button');\n"
    @"      b.className='tool';b.textContent=tk.title;b.title=tk.name+'  '+(tk.desc||'');\n"
    @"      b.setAttribute('data-name',tk.name);\n"
    @"      b.onclick=function(){callToolByName(this.getAttribute('data-name'));};\n"
    @"      box.appendChild(b);\n"
    @"    }\n"
    @"  }\n"
    @"  if(!toolCache.length){box.textContent='没有工具';}\n"
    @"}\n"
    @"function callToolByName(name){\n"
    @"  var t=null;\n"
    @"  for(var i=0;i<toolCache.length;i++){if(toolCache[i].name===name){t=toolCache[i];break;}}\n"
    @"  if(!t){return;}\n"
    @"  var args={};\n"
    @"  var ps=t.params||[];\n"
    @"  for(var i=0;i<ps.length;i++){\n"
    @"    var p=ps[i];\n"
    @"    var label=p.name+(p.desc?('  '+p.desc):'')+(p.required?'  [必填]':'');\n"
    @"    var v=prompt(label,'');\n"
    @"    if(v===null){return;}\n"
    @"    if(v!==''){args[p.name]=v;}\n"
    @"  }\n"
    @"  say('> '+t.name+'  '+JSON.stringify(args),'in');\n"
    @"  fetch('/api/tool',{method:'POST',body:JSON.stringify({name:t.name,args:args})})\n"
    @"    .then(function(r){return r.json();})\n"
    @"    .then(function(j){\n"
    @"      if(!j.ok){say('ERROR: '+j.error,'err');return;}\n"
    @"      var r=j.result;\n"
    @"      if(typeof r==='string'){\n"
    @"        var ls=r.split('\\n');\n"
    @"        if(ls.length>60){say(ls.slice(0,60).join('\\n'));say('... 共 '+ls.length+' 行');}\n"
    @"        else{say(r);}\n"
    @"      }else{\n"
    @"        say(JSON.stringify(r,null,1));\n"
    @"      }\n"
    @"    }).catch(function(e){say('fail: '+e,'err');});\n"
    @"}\n"
    @"document.getElementById('brun').onclick=run;\n"
    @"document.getElementById('bshot').onclick=function(){window.open('/api/screenshot.jpg?t='+Date.now(),'_blank');};\n"
    @"document.getElementById('bui').onclick=function(){textApi('/api/ui');};\n"
    @"document.getElementById('bvc').onclick=function(){textApi('/api/ui?vc=1');};\n"
    @"document.getElementById('bcls').onclick=function(){\n"
    @"  var k=prompt('类名关键字（留空=取前200个）','ViewController');\n"
    @"  if(k===null){return;}\n"
    @"  fetch('/api/classes?q='+encodeURIComponent(k)).then(function(r){return r.json();}).then(function(j){\n"
    @"    say('classes: '+j.count+' total, match '+j.items.length);\n"
    @"    say(j.items.join('\\n'));\n"
    @"  });\n"
    @"};\n"
    @"document.getElementById('bhooks').onclick=function(){\n"
    @"  fetch('/api/hooks').then(function(r){return r.json();}).then(function(j){\n"
    @"    if(!j.items||!j.items.length){say('还没有 hook 规则');return;}\n"
    @"    for(var i=0;i<j.items.length;i++){\n"
    @"      var h=j.items[i];\n"
    @"      say(h.mode+'  '+(h.class_method?'+':'-')+'['+h.cls+' '+h.sel+']  hits='+h.hits);\n"
    @"    }\n"
    @"  });\n"
    @"};\n"
    @"document.getElementById('bcls2').onclick=function(){\n"
    @"  paused=!paused;\n"
    @"  this.textContent=paused?'已暂停':'日志开关';\n"
    @"  if(!paused){poll();}\n"
    @"};\n"
    @"document.getElementById('bclear').onclick=function(){logEl.innerHTML='';fetch('/api/clear');};\n"
    @"document.getElementById('btools').onclick=function(){\n"
    @"  document.getElementById('tools').classList.toggle('show');\n"
    @"};\n"
    @"var hist=[],hi=0;\n"
    @"document.getElementById('cmd').addEventListener('keydown',function(e){\n"
    @"  if(e.key==='Enter'){if(e.target.value.trim()){hist.push(e.target.value);hi=hist.length;}run();}\n"
    @"  else if(e.key==='ArrowUp'){if(hi>0){hi--;e.target.value=hist[hi]||'';}e.preventDefault();}\n"
    @"  else if(e.key==='ArrowDown'){if(hi<hist.length-1){hi++;e.target.value=hist[hi]||'';}else{hi=hist.length;e.target.value='';}e.preventDefault();}\n"
    @"});\n"
    @"loadInfo();\n"
    @"loadTools();\n"
    @"poll();\n"
    @"setInterval(poll,700);\n"
    @"</script></body></html>\n";
}
